interface I18nContextValue {
  language: LanguageCode
  setLanguage: (language: LanguageCode) => void
  options: Array<{ value: LanguageCode; label: string }>
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined)

export function I18nProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<LanguageCode>(i18n.language as LanguageCode)

  useEffect(() => {
    void i18n.changeLanguage(language)
    window.localStorage.setItem(STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage(nextLanguage) {
        setLanguageState(nextLanguage)
      },
      options: languageOptions,
    }),
    [language],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18nSettings() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error('useI18nSettings 必须在 I18nProvider 内使用')
  }
  return context
}

